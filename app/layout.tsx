import type { Metadata, Viewport } from "next";
import { Cormorant_Garamond, Manrope } from "next/font/google";
import localFont from "next/font/local";
import { APP_NAME, APP_TAGLINE, APP_TITLE, COMPANY_NAME } from "@/lib/brand";
import { THEME_STORAGE_KEY } from "@/lib/theme";
import { displayPrefsScript } from "@/lib/display-prefs";
import "./globals.css";
import { ServiceWorker } from "@/components/ServiceWorker";
import { ErrorReporter } from "@/components/ErrorReporter";
import { LaunchSplash } from "@/components/brand/LaunchSplash";

// Self-hosted by next/font: no request to Google at runtime and no layout
// shift while the font loads.
const sans = Manrope({ subsets: ["latin"], variable: "--font-sans", display: "swap" });
// Cormorant Garamond: a high-contrast engraved serif for headings — the
// letterhead of a private bank rather than a web app.
// Great Vibes: the flowing script of the Grace and Grace-bound Ventures
// wordmarks (SIL OFL, bundled for the poster editor too).
const script = localFont({ src: "../public/fonts/poster/great-vibes.woff2", variable: "--font-script", display: "swap" });
const display = Cormorant_Garamond({ subsets: ["latin"], weight: ["500", "600", "700"], style: ["normal", "italic"], variable: "--font-display", display: "swap" });

export const metadata: Metadata = {
  title: { default: APP_TITLE, template: `%s · ${APP_NAME}` },
  description: `${APP_TAGLINE} By ${COMPANY_NAME}.`,
  applicationName: APP_NAME,
  creator: COMPANY_NAME,
  // iPhone/iPad "Add to Home Screen": open full screen with this name. The
  // status bar uses the page's theme colour ("default" keeps it out of the
  // way of content, so pages don't need top padding for it).
  appleWebApp: { capable: true, title: APP_NAME, statusBarStyle: "default" },
  // Generated by scripts/build-brand.mjs (the Grace cross).
  icons: { icon: "/icons/favicon-32.png", apple: "/icons/apple-touch-icon.png" },
  // Stop iOS turning numbers (amounts, dates) into phone links.
  formatDetection: { telephone: false },
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  // Draw edge to edge; globals.css and the shell pad for the home indicator
  // and landscape notch with env(safe-area-inset-*).
  viewportFit: "cover",
  // Android: the keyboard shrinks the page instead of covering it, so inputs
  // pinned to the bottom (chat) stay visible. iPhone: components/KeyboardViewport.tsx.
  interactiveWidget: "resizes-content",
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#FDF7F8" },
    { media: "(prefers-color-scheme: dark)", color: "#140A19" },
  ],
};

// Runs before the page paints, so someone who chose "Dark" (or "Light")
// never sees a flash of the other theme. "system" leaves the attribute off
// and the CSS media query decides. Wrapped in try: storage can be blocked.
// Installed app, first page of this launch: show the name splash (see LaunchSplash).
const launchSplash = `try{if((matchMedia("(display-mode: standalone)").matches||navigator.standalone)&&!sessionStorage.getItem("grace-launched")){sessionStorage.setItem("grace-launched","1");document.documentElement.dataset.launch=""}}catch(e){}`;
const applySavedTheme = `try{var t=localStorage.getItem(${JSON.stringify(THEME_STORAGE_KEY)});if(t==="light"||t==="dark")document.documentElement.dataset.theme=t}catch(e){}`;

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    // suppressHydrationWarning: the script above may set data-theme before React hydrates.
    <html lang="en" className={`${sans.variable} ${display.variable} ${script.variable}`} suppressHydrationWarning>
      <head>
        <script dangerouslySetInnerHTML={{ __html: applySavedTheme + displayPrefsScript + launchSplash }} />
      </head>
      <body>
        <LaunchSplash />
        {children}
        {/* On every page (not just the dashboard), so an installed app opened
            offline on the sign-in screen still gets the offline page. */}
        <ServiceWorker />
        <ErrorReporter />
      </body>
    </html>
  );
}
